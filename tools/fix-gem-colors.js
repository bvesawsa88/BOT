let n = 0;
cards.forEach(c => {
  let next = null;
  if (BY_CODE[c.code] != null) next = BY_CODE[c.code];
  else if (BY_NAME_WHITE.has(c.name)) next = 'ขาว';
  if (next != null && c.gemColor !== next) {
    c.gemColor = next;
    n++;
  }
});
fs.writeFileSync(file, JSON.stringify(cards));
console.log('updated gemColor on', n, 'rows');

const sd01Path = path.join(__dirname, '..', 'data', 'sd01.json');
if (fs.existsSync(sd01Path)) {
  const sd01 = JSON.parse(fs.readFileSync(sd01Path, 'utf8'));
  const byUid = new Map(cards.map(c => [c.uid, c]));
  let m = 0;
  sd01.forEach((c, i) => {
    const src = byUid.get(c.uid) || cards.find(x => x.code === c.code && x.rarity === c.rarity);
    if (src && c.gemColor !== src.gemColor) {
      sd01[i] = Object.assign({}, c, { gemColor: src.gemColor });
      m++;
    }
  });
  if (m) {
    fs.writeFileSync(sd01Path, JSON.stringify(sd01));
    console.log('synced sd01.json gemColor on', m, 'rows');
  }
}
